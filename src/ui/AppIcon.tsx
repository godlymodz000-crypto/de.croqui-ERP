/** Usa o Icon do design system quando ele tem o ícone; senão, um dos ícones acima. */
export function AppIcon({ name, size = 20 }: { name: string; size?: number }) {
  if (ICON_NAMES.includes(name)) return <Icon name={name} size={size} />;
  const body = EXTRA[name];
  if (!body) return null;
  return (
    <svg
      xmlns="http://www.w3.org/2000/svg"
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={1.25}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden
      style={{ display: 'inline-block', flexShrink: 0, verticalAlign: 'middle' }}
      dangerouslySetInnerHTML={{ __html: body }}
    />
  );
}
